    private fun format(raw: RawFacts): Facts {
        val born = SimpleDateFormat("yyyy年M月d日", Locale.CHINA).format(Date(raw.firstInstallTime))
        val days = raw.days()
        val age = if (days < 1) "不到一天" else "${days}天"
        val size = if (raw.apkBytes > 0) String.format(Locale.CHINA, "%.1f MB", raw.apkBytes / 1_048_576.0) else "不少"
        return Facts(raw.name, born, age, size)
    }

